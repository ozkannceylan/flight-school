#!/usr/bin/env python3
"""Concatenate content/ + lab READMEs into per-phase NotebookLM packs.

Direction is one-way: repo → build/. Nothing writes back into content/.

    python tools/studypack.py
    python tools/studypack.py --phase 3
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content"
LABS = ROOT / "labs"
BUILD = ROOT / "build"

# One pack per PLAN phase. Phase 1 includes Lab 00 (the Phase 0 exemplar).
